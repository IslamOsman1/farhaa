export default function Features({ language = 'ar' }) {
  const sectionRef = useRef(null);
  const copy = landingCopy[language].features;

  useEffect(() => {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add('active');
          }
        });
      },
      { threshold: 0.1 },
    );

    const cards = sectionRef.current.querySelectorAll('.reveal');
    cards.forEach((card) => observer.observe(card));

    return () => {
      cards.forEach((card) => observer.unobserve(card));
    };
  }, []);

  return (
    <section id="features" className="section features-section" ref={sectionRef}>
      <h2 className="section-title reveal">{copy.title}</h2>
      <p className="section-subtitle reveal">{copy.subtitle}</p>

      <div className="features-grid">
        {copy.items.map((feat, idx) => (
          <div key={idx} className="feature-card reveal" style={{ transitionDelay: `${idx * 0.1}s` }}>
            <div className="feature-icon">{icons[idx]}</div>
            <h3 className="feature-title">{feat[0]}</h3>
            <p>{feat[1]}</p>
          </div>
        ))}
      </div>
    </section>
  );
}
